def main():
    docs = json.loads((ROOT / "data/documents.json").read_text(encoding="utf-8"))[:8]
    docs += [
        dict(
            doc_id=f"D{i:02}",
            title=t,
            topic=topic,
            version_date="2025-09-01",
            effective_date=None,
            scope=scope,
            status="published",
            content=content,
        )
        for i, (t, topic, content, scope) in enumerate(ROWS, 9)
    ]
    write_json(ROOT / "data/documents.json", docs)
    items = []
    for i, (question, ids) in enumerate(QUESTIONS, 1):
        items.append(
            {
                "id": f"Q{i:02}",
                "question": question,
                "category": "conflict"
                if ids == ["D01", "D02"]
                else "answerable"
                if ids
                else "unanswerable",
                "expected_doc_ids": ids,
                "expected_status": "NEEDS_CLARIFICATION"
                if ids == ["D01", "D02"]
                else "COMPLETED"
                if ids
                else "INSUFFICIENT_EVIDENCE",
                "expected_facts": [
                    docs[int(d[1:]) - 1]["content"].split("。")[0] + "。" for d in ids
                ],
                "answerability": bool(ids),
                "optional_history": [],
            }
        )
    (ROOT / "data/eval_questions.jsonl").write_text(
        "\n".join(json.dumps(i, ensure_ascii=False) for i in items) + "\n", encoding="utf-8"
    )
    write_json(ROOT / "data/gold_labels.json", {i["id"]: i["expected_doc_ids"] for i in items})
    print(
        f"Declared {len(docs)} synthetic documents, {len(items)} questions; {sum(i['answerability'] for i in items)} answerable."
    )


if __name__ == "__main__":
    main()
